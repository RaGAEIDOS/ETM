import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Scans public/mascot for the designer's banner/cutout files and writes a
 * static manifest consumed by <HeroBanner /> and /about. Runs automatically
 * before `npm run dev` and `npm run build`, so dropping a real
 * maryam_banner.png / maryam_cutout.png needs no code change.
 */
const root = process.cwd();
const dir = join(root, "public", "mascot");
const url = (name) => `/mascot/${name}`;
const has = (name) => existsSync(join(dir, name));

function asset(base, placeholder, widths) {
  const png = has(`${base}.png`) ? url(`${base}.png`) : null;
  const webp = has(`${base}.webp`) ? url(`${base}.webp`) : null;
  const sizes = widths
    .map((width) => ({ width, path: has(`${base}-${width}.webp`) ? url(`${base}-${width}.webp`) : null }))
    .filter((item) => item.path);
  const srcSet = sizes.length ? sizes.map((item) => `${item.path} ${item.width}w`).join(", ") : null;

  return {
    png,
    webp,
    srcSet,
    placeholder: url(placeholder),
    available: Boolean(png || webp || srcSet),
  };
}

const assets = {
  banner: asset("maryam_banner", "maryam_banner.svg", [480, 768, 1280, 1920]),
  cutout: asset("maryam_cutout", "maryam_cutout.svg", []),
  icon: url("maryam_icon.svg"),
};

const output = `/* AUTO-GENERATED by scripts/generate-mascot-manifest.mjs. Do not edit. */
export type MascotAsset = {
  png: string | null;
  webp: string | null;
  srcSet: string | null;
  placeholder: string;
  available: boolean;
};

export const MASCOT_ASSETS: {
  banner: MascotAsset;
  cutout: MascotAsset;
  icon: string;
} = ${JSON.stringify(assets, null, 2)};
`;

writeFileSync(join(root, "lib", "mascot-assets.ts"), output);
console.log(
  `[mascot-assets] banner=${assets.banner.available ? "real" : "placeholder"} ` +
    `cutout=${assets.cutout.available ? "real" : "placeholder"}`
);
